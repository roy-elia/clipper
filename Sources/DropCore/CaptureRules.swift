import Foundation
import CryptoKit

/// Decides whether a pasteboard snapshot may be stored and what kind it is.
public struct PasteboardSnapshot: Sendable {
    public var types: Set<String>
    public var string: String?
    public var data: Data?
    public var sourceBundleID: String?
    public var extras: [String: Data]
    public var fileURLs: [String]
    public init(types: Set<String>, string: String? = nil, data: Data? = nil, sourceBundleID: String? = nil,
                extras: [String: Data] = [:], fileURLs: [String] = []) {
        self.types = types; self.string = string; self.data = data; self.sourceBundleID = sourceBundleID
        self.extras = extras; self.fileURLs = fileURLs
    }
}

public struct CaptureRules: Sendable {
    public static let concealed = "org.nspasteboard.ConcealedType"
    public static let transient = "org.nspasteboard.TransientType"
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"

    public var ignoredBundleIDs: Set<String>
    public var maxBytes: Int
    /// Skip clips other apps mark as passwords (concealed) or as temporary (transient, auto-generated).
    public var ignoreConfidential = true
    public var ignoreTransient = true

    public init(ignoredBundleIDs: Set<String> = CaptureRules.defaultIgnored, maxBytes: Int = 20_000_000) {
        self.ignoredBundleIDs = ignoredBundleIDs; self.maxBytes = maxBytes
    }

    public static let defaultIgnored: Set<String> = [
        "com.1password.1password", "com.agilebits.onepassword-osx", "com.agilebits.onepassword7",
        "com.apple.Passwords", "com.apple.keychainaccess",
    ]

    public func shouldCapture(_ s: PasteboardSnapshot) -> Bool {
        if ignoreConfidential, s.types.contains(Self.concealed) { return false }
        if ignoreTransient, !s.types.isDisjoint(with: [Self.transient, Self.autoGenerated]) { return false }
        if let b = s.sourceBundleID, ignoredBundleIDs.contains(b) { return false }
        if let d = s.data, d.count > maxBytes { return false }
        return s.string?.isEmpty == false || s.data != nil || !s.fileURLs.isEmpty
    }

    public func kind(of s: PasteboardSnapshot) -> ClipKind {
        if s.types.contains("public.file-url") || !s.fileURLs.isEmpty { return .file }
        if s.types.contains("public.png") || s.types.contains("public.tiff") || s.types.contains("public.jpeg") { return .image }
        if let t = s.string?.trimmingCharacters(in: .whitespacesAndNewlines) {
            if Self.isLink(t) { return .link }
            if Self.isHexColor(t) { return .color }
        }
        return .text
    }

    static func isLink(_ t: String) -> Bool {
        guard !t.contains(where: \.isWhitespace), let u = URL(string: t), let s = u.scheme?.lowercased() else { return false }
        return ["http", "https"].contains(s) && u.host != nil
    }

    static func isHexColor(_ t: String) -> Bool {
        guard t.hasPrefix("#") else { return false }
        let h = t.dropFirst()
        return [3, 6, 8].contains(h.count) && h.allSatisfy(\.isHexDigit)
    }

    public static func checksum(string: String?, data: Data?) -> String {
        var h = SHA256()
        if let s = string { h.update(data: Data(s.utf8)) }
        if let d = data { h.update(data: d) }
        return h.finalize().map { String(format: "%02x", $0) }.joined()
    }

    public func makeItem(from s: PasteboardSnapshot, now: Date = Date()) -> ClipItem? {
        guard shouldCapture(s) else { return nil }
        let k = kind(of: s)
        let text = s.string ?? (s.fileURLs.isEmpty ? nil : s.fileURLs.compactMap { URL(string: $0)?.path }.joined(separator: "\n"))
        let title = (k == .file && !s.fileURLs.isEmpty ? s.fileURLs.compactMap { URL(string: $0)?.lastPathComponent }.joined(separator: ", ") : (text ?? k.rawValue)).split(whereSeparator: \.isNewline).first.map(String.init)?.prefix(120).description ?? k.rawValue
        let kept = s.extras.filter { $0.value.count <= 2_000_000 }
        return ClipItem(kind: k, title: title, text: text, data: s.data, sourceBundleID: s.sourceBundleID,
                        checksum: Self.checksum(string: text, data: s.data), createdAt: now,
                        extras: kept.isEmpty ? nil : kept, fileURLs: s.fileURLs.isEmpty ? nil : s.fileURLs,
                        sensitive: (k == .text || k == .link) && text.map({ SecretDetector.classify($0) != nil }) == true ? true : nil)
    }
}
